export const compileTFileXML = (file: TFile): string => {
  let xml = `<?xml version="1.0" encoding="utf-8"?>\n`;
  xml += `<language id="${escapeXmlAttr(file.languageId)}">\n`;
  (file.pages || []).forEach((page) => {
    const title = page.title ? ` title="${escapeXmlAttr(page.title)}"` : '';
    xml += `  <page id="${escapeXmlAttr(page.id)}"${title}>\n`;
    (page.items || []).forEach((item) => {
      const comment = item.description ? ` <!-- ${escapeXmlText(item.description)} -->` : '';
      xml += `    <t id="${escapeXmlAttr(item.id)}">${escapeXmlText(item.value)}</t>${comment}\n`;
    });
    xml += `  </page>\n`;
  });
  xml += `</language>`;
  return xml;
};

export const compileDiffDocument = (patches: PatchBlock[], targetFile: string): string => {
  let xml = `<?xml version="1.0" encoding="utf-8"?>\n`;
  xml += `<!-- XML Diff patch targeting file: "${escapeXmlAttr(targetFile)}" -->\n`;
  xml += `<diff>\n\n`;
  patches.forEach((b) => {
    if (b.note) {
      xml += `  <!-- Patch Note: ${escapeXmlText(b.note)} -->\n`;
    }
    if (b.action === 'remove') {
      xml += `  <remove sel="${escapeXmlAttr(b.sel)}" />\n\n`;
    } else if (b.action === 'add' && b.attrType) {
      // Attribute-level add (T4.2): <add sel="..." type="@attr">value</add>
      xml += `  <add sel="${escapeXmlAttr(b.sel)}" type="${escapeXmlAttr(b.attrType)}">${escapeXmlText((b.content || '').trim())}</add>\n\n`;
    } else if (b.action === 'replace' && b.sel.includes('/@')) {
      // Attribute-value replace: single-line escaped text body
      xml += `  <replace sel="${escapeXmlAttr(b.sel)}">${escapeXmlText((b.content || '').trim())}</replace>\n\n`;
    } else {
      const posAttr = (b.action === 'add' && b.pos) ? ` pos="${escapeXmlAttr(b.pos)}"` : '';
      const raw = (b.content || '').trim();
      // P4: malformed content must NOT compile silently into <diff>. Emit a loud comment
      // marker instead of a broken element (`--` neutralised so it can't close the comment).
      if (!isWellFormedXmlFragment(raw)) {
        xml += `  <!-- INVALID PATCH CONTENT (sel="${escapeXmlAttr(b.sel)}") — fix in the XML Patching workbench before shipping: ${escapeXmlText(raw).replace(/--/g, '- -')} -->\n\n`;
      } else {
        xml += `  <${b.action} sel="${escapeXmlAttr(b.sel)}"${posAttr}>\n`;
        const lines = raw.split('\n').filter((l: string) => l.trim().length > 0);
        lines.forEach((l: string) => {
          xml += `    ${l}\n`;
        });
        xml += `  </${b.action}>\n\n`;
      }
    }
  });
  xml += `</diff>`;
  return xml;
};

/**
 * True when the modeled workspace owns a generated Mission Director document.
 * Source-owned MD passthrough/original files are deliberately excluded: the artifact
 * pipeline preserves those bytes and must not manufacture a second generated script.
 */
export const hasGeneratedMdDomain = (workspace: ModWorkspace): boolean => {
  return (workspace.nodes || []).some(node => node.includeInBuild !== false);
};

/** True when this extension actually contains any Mission Director domain. */
export const hasAnyMdDomain = (workspace: ModWorkspace): boolean => {
  if (hasGeneratedMdDomain(workspace)) return true;
  if (workspace.mdOriginal?.content) return true;
  if ((workspace.originalFiles || []).some(file => file.kind === 'md' || /(^|[\\/])md[\\/].*\.xml$/i.test(file.path))) return true;
  return (workspace.passthroughFiles || []).some(file => /(^|[\\/])md[\\/].*\.xml$/i.test(file.path));
};

/**
 * True when the extension contains deployable authored behavior or data beyond its manifest.
 * An inert legacy MD shell is deliberately not output: data-only mods do not need a placebo cue.
 */
export const hasEffectiveAuthoredOutput = (workspace: ModWorkspace): boolean => {
  const enabled = (key: keyof NonNullable<ModWorkspace['compileSettings']>) => workspace.compileSettings?.[key] !== false;
  const included = <T extends { includeInBuild?: boolean }>(items: T[] | undefined) => (items || []).some(item => item.includeInBuild !== false);
  const sourceMd = [
    ...(workspace.mdOriginal?.content ? [workspace.mdOriginal.content] : []),
    ...(workspace.originalFiles || []).filter(file => file.kind === 'md' || /(^|[\\/])md[\\/].*\.xml$/i.test(file.path)).map(file => file.content),
    ...(workspace.passthroughFiles || []).filter(file => /(^|[\\/])md[\\/].*\.xml$/i.test(file.path)).map(file => file.content || ''),
  ];
  const sourceHasMdEntry = sourceMd.some(content => /<(?:cue|library)\b/.test(content));
  const passthroughHasPayload = (workspace.passthroughFiles || []).some(file => {
    const normalized = file.path.replace(/\\/g, '/').toLowerCase();
    if (normalized === 'content.xml' || /(^|\/)readme(?:\.[^/]*)?$/.test(normalized)) return false;
    if (/^md\/.*\.xml$/.test(normalized)) return /<(?:cue|library)\b/.test(file.content || '');
    return true;
  });
  const modeledOriginalHasPayload = (workspace.originalFiles || []).some(file => {
    if (file.kind === 'content' || file.kind === 'readme') return false;
    if (file.kind === 'md') return /<(?:cue|library)\b/.test(file.content || '');
    return true;
  });

  return (enabled('md') && (hasGeneratedMdDomain(workspace) || sourceHasMdEntry))
    || (enabled('ui') && included(workspace.uiWidgets))
    || (enabled('ai') && included(workspace.aiScripts))
    || (enabled('library') && (included(workspace.wares) || included(workspace.jobs)))
    || (enabled('translations') && included(workspace.tFiles))
    || (enabled('patches') && included(workspace.xmlPatches))
    || (enabled('ui') && !!workspace.customLua?.trim())
    || !!workspace.integrationContract
    || modeledOriginalHasPayload
    || passthroughHasPayload;
};

export const validatePackageReadiness = (workspace: ModWorkspace, artifactId?: string): PackageDiagnostic[] => {
  const reports: PackageDiagnostic[] = [];
  const modId = artifactId?.trim() || resolveWorkspaceArtifactId(workspace);

  if (!workspace.name?.trim()) {
    reports.push({
      severity: 'error',
      message: 'Compiled extension needs a mod name. This becomes the content.xml name and package folder.',
      category: 'egosoft'
    });
  }

  if (!/^[a-z0-9_]+$/.test(modId)) {
    reports.push({
      severity: 'error',
      message: `Compiled extension id "${modId}" must use lowercase letters, numbers, and underscores only.`,
      category: 'egosoft'
    });
  }

  if (!workspace.author?.trim()) {
    reports.push({
      severity: 'warning',
      message: 'Compiled content.xml has no explicit author. Set Mod Meta author before shipping.',
      category: 'egosoft'
    });
  }

  if (!workspace.description?.trim()) {
    reports.push({
      severity: 'warning',
      message: 'Compiled content.xml has no explicit description. Manual users need this in the Extensions menu.',
      category: 'egosoft'
    });
  }

  // Cues can come from the node graph OR from hand-authored MD preserved verbatim. A libraries-only,
  // asset-only, UI-only, or diff-only extension has NO MD domain and therefore needs no cue at all.
  // Only diagnose an entry point when the extension actually contains MD bytes/model nodes.
  const hasGraphCue = workspace.nodes.some(node => node.type === 'cue');
  const sourceMd = [
    ...(workspace.mdOriginal?.content ? [workspace.mdOriginal.content] : []),
    ...(workspace.originalFiles ?? []).filter(file => file.kind === 'md' || /(^|[\\/])md[\\/].*\.xml$/i.test(file.path)).map(file => file.content),
    ...(workspace.passthroughFiles ?? []).filter(file => /(^|[\\/])md[\\/].*\.xml$/i.test(file.path)).map(file => file.content ?? ''),
  ];
  const hasSourceEntryPoint = sourceMd.some(content => /<(?:cue|library)\b/.test(content));
  const hasValidContractMd = !!workspace.integrationContract
    && validateContract(workspace.integrationContract).every(finding => finding.severity !== 'error');
  if (hasGeneratedMdDomain(workspace) && !hasGraphCue && !hasValidContractMd) {
    reports.push({
      severity: 'error',
      code: 'package.md_missing_entrypoint',
      message: 'Modeled Mission Director output has no cue or library entry point. Add real MD logic, or exclude the unused MD nodes from the build.',
      category: 'egosoft'
    });
  } else if (hasAnyMdDomain(workspace) && !hasGraphCue && !hasSourceEntryPoint && !hasValidContractMd) {
    reports.push({
      severity: 'warning',
      code: 'package.md_inert_source',
      message: 'An imported MD file has no cue or library entry point. Data-only XML patch, wares, jobs, and asset mods do not need a cue—remove or exclude the unused MD file instead of adding a placebo cue.',
      category: 'egosoft'
    });
  }

  if (!hasEffectiveAuthoredOutput(workspace)) {
    reports.push({
      severity: 'error',
      code: 'package.empty_extension',
      message: 'The extension has no effective authored output. Add a data patch, ware/job/asset, UI, AI script, translation, Lua file, or real Mission Director cue/library before packaging.',
      category: 'egosoft'
    });
  }

  // P5: custom Lua is written verbatim to ui/<id>_custom.lua when UI output is enabled, so
  // analyze the exact bytes that the package will contain and carry every analyzer finding
  // through without changing its severity, location, code, or message.
  const customLuaPath = `ui/${modId}_custom.lua`;
  if (workspace.compileSettings?.ui !== false && workspace.customLua && workspace.customLua.trim()) {
    try {
      const lua = analyzeLuaFiles([{
        rel: customLuaPath,
        text: workspace.customLua,
        source: 'loose',
        sourcePath: customLuaPath,
        extension: { folder: modId, id: modId, name: workspace.name },
      }]);
      for (const f of lua.findings) {
        reports.push({
          severity: f.severity,
          code: f.code,
          filePath: f.sourcePath || f.rel || customLuaPath,
          line: f.line,
          message: f.message,
          domain: 'ui_layout',
          category: 'egosoft'
        });
      }
    } catch {
      reports.push({
        severity: 'info',
        code: 'x4-ui.analysis-unavailable',
        filePath: customLuaPath,
        message: 'Custom Lua was not statically verified because the Lua analyzer failed unexpectedly. Package readiness is not clean; inspect the analyzer failure before relying on this output.',
        domain: 'ui_layout',
        category: 'egosoft'
      });
    }
  }

  return reports;
};

export function runPackageReadinessParitySelftest() {
  const checks: { name: string; pass: boolean; detail?: unknown }[] = [];
  const ok = (name: string, pass: boolean, detail?: unknown) => checks.push({ name, pass, detail });
  const base = {
    id: 'package_parity_fixture',
    name: 'Package Parity Fixture',
    version: '1.0.0',
    author: 'Forge',
    description: 'Parity fixture',
    nodes: [],
    links: [],
    uiWidgets: [],
    uiTheme: { backgroundColor: '#000', borderColor: '#000', accentColor: '#0ff', opacity: 1, showIcons: true },
    compileSettings: { md: false, ui: true, ai: false, library: false, translations: false, patches: false },
  } as ModWorkspace;

  const importedIdentity = {
    ...base,
    sourceFolder: 'F:\\Mods\\x4_ai_influence - Copy\\',
    contentId: 'x4_ai_influence',
    name: 'AI Influence Friendly Name',
    customLua: 'frame:addTable(13)',
  };
  const importedIdentityFinding = validatePackageReadiness(importedIdentity)
    .find(finding => finding.code === 'x4-ui.add-table-column-limit');
  ok(
    'artifact_id_prefers_source_folder_over_content_id_and_name',
    resolveWorkspaceArtifactId(importedIdentity) === 'x4_ai_influence_copy',
    resolveWorkspaceArtifactId(importedIdentity),
  );
  ok(
    'readiness_diagnostic_path_matches_resolved_artifact_id',
    importedIdentityFinding?.filePath === 'ui/x4_ai_influence_copy_custom.lua',
    importedIdentityFinding,
  );
  ok(
    'artifact_id_uses_valid_content_id_when_source_folder_is_absent',
    resolveWorkspaceArtifactId({ ...base, contentId: 'valid.content-id', name: 'Display Name' }) === 'valid.content-id',
    resolveWorkspaceArtifactId({ ...base, contentId: 'valid.content-id', name: 'Display Name' }),
  );
  ok(
    'artifact_id_falls_back_to_safe_name_for_invalid_content_id',
    resolveWorkspaceArtifactId({ ...base, contentId: 'invalid content/id', name: 'Friendly Name' }) === 'friendly_name',
    resolveWorkspaceArtifactId({ ...base, contentId: 'invalid content/id', name: 'Friendly Name' }),
  );

  const fatal = validatePackageReadiness({
    ...base,
    name: 'Parity Fatal',
    customLua: 'frame:addTable(24)',
  });
  const fatalFinding = fatal.find(finding => finding.code === 'x4-ui.add-table-column-limit');
  ok(
    'readiness_preserves_fatal_lua_location_and_failure_mode',
    fatalFinding?.severity === 'error'
      && fatalFinding.filePath === 'ui/parity_fatal_custom.lua'
      && fatalFinding.line === 1
      && fatalFinding.domain === 'ui_layout'
      && fatalFinding.message.includes('Failure mode: Engine refuses the ENTIRE frame')
      && !fatalFinding.message.includes("Custom Lua won't compile"),
    fatalFinding,
  );

  const warning = validatePackageReadiness({
    ...base,
    name: 'Parity Warning',
    customLua: [
      'local menu = { name = "sample" }',
      'menu.frame = Helper.createFrameHandle(menu)',
      'Helper.registerMenu(menu)',
      'OpenMenu(menu.name)',
      'local table = menu.frame:addTable(2, { width = 100, height = 100 })',
      'table:addRow({{ text = "a" }, { text = "b" }}, { height = 200 })',
    ].join('\n'),
  });
  const warningFinding = warning.find(finding => finding.code === 'x4-ui.row-height-budget');
  ok(
    'readiness_preserves_x4_warning_without_blocking',
    warningFinding?.severity === 'warning'
      && warningFinding.filePath === 'ui/parity_warning_custom.lua'
      && warningFinding.domain === 'ui_layout'
      && warningFinding.message.includes('Literal row heights sum to 200')
      && !warning.some(finding => finding.severity === 'error'),
    warningFinding,
  );

  const dynamic = validatePackageReadiness({
    ...base,
    name: 'Parity Dynamic',
    customLua: 'frame:addTable(columns)',
  });
  const dynamicFinding = dynamic.find(finding => finding.code === 'x4-ui.verification-gap');
  ok(
    'readiness_keeps_dynamic_ui_nonblocking_and_explicit',
    dynamicFinding?.severity === 'info'
      && dynamicFinding.filePath === 'ui/parity_dynamic_custom.lua'
      && dynamicFinding.domain === 'ui_layout'
      && dynamicFinding.message.includes('Not statically verified')
      && !dynamic.some(finding => finding.severity === 'error' && finding.code === 'x4-ui.verification-gap'),
    dynamicFinding,
  );

  const disabled = { ...base, name: 'Parity Disabled', compileSettings: { ...base.compileSettings, ui: false }, customLua: 'return true' };
  const disabledReports = validatePackageReadiness(disabled);
  ok(
    'disabled_custom_lua_is_not_effective_authored_output',
    !hasEffectiveAuthoredOutput(disabled)
      && disabledReports.some(finding => finding.code === 'package.empty_extension' && finding.severity === 'error'),
    disabledReports,
  );

  const suppliedArtifact = validatePackageReadiness({
    ...base,
    name: 'Display Name Is Not The Artifact Id',
    customLua: 'frame:addTable(13)',
  }, 'imported_artifact_id');
  const suppliedArtifactFinding = suppliedArtifact.find(finding => finding.code === 'x4-ui.add-table-column-limit');
  ok(
    'readiness_uses_supplied_artifact_id_for_custom_lua_path',
    suppliedArtifactFinding?.filePath === 'ui/imported_artifact_id_custom.lua'
      && suppliedArtifactFinding.domain === 'ui_layout',
    suppliedArtifactFinding,
  );

  const passed = checks.filter(check => check.pass).length;
  return { allPassed: passed === checks.length, pass: passed === checks.length, passed, total: checks.length, checks };
}
